"""Render a config as TOML (for ``syntasks config show``)."""

import dataclasses
import json
from typing import Any

from syntasks.config.schema import Config
from syntasks.units import format_duration

__all__ = ["dump_config"]


def _key(name: str) -> str:
    return (
        name if name.replace("_", "").replace("-", "").isalnum() else json.dumps(name)
    )


def _value(value: Any, unit: str | None) -> str:  # noqa: PLR0911
    if (
        unit == "duration"
        and isinstance(value, (int, float))
        and not isinstance(value, bool)
    ):
        return json.dumps(format_duration(value))
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, list):
        return "[" + ", ".join(_value(v, None) for v in value) + "]"
    if isinstance(value, dict):
        inner = ", ".join(f"{_key(k)} = {_value(v, None)}" for k, v in value.items())
        return "{ " + inner + " }" if inner else "{}"
    return json.dumps(str(value))


def _section(
    lines: list[str],
    header: str,
    obj: Any,
    sources: dict[str, str] | None,
    path: str,
    skip_none: bool,
) -> None:
    body: list[str] = []
    nested: list[tuple[str, Any, str]] = []
    for f in dataclasses.fields(obj):
        if f.metadata.get("internal"):
            continue
        value = getattr(obj, f.name)
        dotted = f"{path}.{f.name}"
        if dataclasses.is_dataclass(value):
            nested.append((f"{header}.{f.name}", value, dotted))
            continue
        if value is None:
            if skip_none:
                continue
            line = f"# {f.name} = (not set)"
        else:
            line = f"{f.name} = {_value(value, f.metadata.get('unit'))}"
        if sources is not None:
            line += f"  # {sources.get(dotted, 'default')}"
        body.append(line)
    lines.append(f"[{header}]")
    lines.extend(body)
    lines.append("")
    for sub_header, sub, sub_path in nested:
        _section(lines, sub_header, sub, sources, sub_path, skip_none)


def dump_config(config: Config, *, with_sources: bool = False) -> str:
    """
    Render the effective configuration as TOML.

    :param config: configuration.
    :param with_sources: add a comment with each value's origin.
    :return: TOML text.
    """
    sources = config.sources if with_sources else None
    lines: list[str] = []
    if config.path:
        lines += [f"# loaded from {config.path}", ""]
    for f in dataclasses.fields(config):
        if f.metadata.get("internal"):
            continue
        value = getattr(config, f.name)
        if isinstance(value, dict):
            for name, item in value.items():
                _section(
                    lines,
                    f"{f.name}.{_key(name)}",
                    item,
                    sources,
                    f"{f.name}.{name}",
                    skip_none=True,
                )
        else:
            _section(lines, f.name, value, sources, f.name, skip_none=False)
    return "\n".join(lines).rstrip() + "\n"


def _type_text(hint: Any) -> str:
    text = str(hint).replace("typing.", "").replace("NoneType", "None")
    text = text.replace("<class '", "").replace("'>", "")
    text = text.replace("syntasks.config.schema.SentinelConfig", "table")
    parts = [part for part in text.split(" | ") if part != "None"]
    return " or ".join(parts)


def config_reference() -> str:
    """
    Markdown reference of every setting (used to build the docs).

    :return: Markdown text.
    """
    from typing import get_type_hints  # noqa: PLC0415

    from syntasks.config import schema  # noqa: PLC0415

    sections = [
        ("app", schema.AppConfig),
        ("redis", schema.RedisConfig),
        ("redis.sentinel", schema.SentinelConfig),
        ("worker", schema.WorkerConfig),
        ("node", schema.NodeConfig),
        ("defaults", schema.TaskDefaults),
        ('tasks."module:function"', schema.TaskConfig),
        ("queues.<name>", schema.QueueConfig),
        ("scheduler", schema.SchedulerConfig),
        ("schedules.<id>", schema.ScheduleConfig),
        ("channels", schema.ChannelsConfig),
        ("results", schema.ResultsConfig),
        ("logging", schema.LoggingConfig),
    ]
    lines = [
        "# Configuration reference",
        "",
        "<!-- Generated by syntasks.config.dump.config_reference(); do not edit. -->",
        "",
        (
            'Units: durations like `"250ms"`, `"30s"`, `"1h30m"` (or seconds); '
            'sizes like `"64KiB"`, `"2GiB"` (or bytes); rates like `"100/s"`.'
        ),
        "",
        (
            "Scope: **node** settings describe one machine; **cluster** settings "
            "must be the same everywhere and are published to Redis on start "
            "(see [Cluster](../guide/cluster.md))."
        ),
        "",
    ]
    for name, cls in sections:
        hints = get_type_hints(cls)
        lines += [
            f"## `[{name}]`",
            "",
            "| Setting | Type | Default | Scope | Description |",
            "|---|---|---|---|---|",
        ]
        instance = None
        try:
            instance = cls()
        except TypeError:
            instance = None
        for f in dataclasses.fields(cls):
            if f.metadata.get("internal"):
                continue
            unit = f.metadata.get("unit")
            default: Any = getattr(instance, f.name, None) if instance else None
            default_text = "-" if default is None else f"`{_value(default, unit)}`"
            kind = unit or _type_text(hints[f.name])
            doc = f.metadata.get("doc", "")
            scope = f.metadata.get("scope", "node")
            lines.append(f"| `{f.name}` | {kind} | {default_text} | {scope} | {doc} |")
        lines.append("")
    return "\n".join(lines)
